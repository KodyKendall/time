//   https://www.mutopiaproject.org/ftp/SousaJP/TheStarsAndStripesForever/
// Onsets, durations, pitches, repeats and the tempo plan (quarter = 240, as LilyPond's
// own \midi block sets it) are Sousa's and the typesetter's, extracted from the MIDI
// LilyPond generates from that edition. Times are stored in MIDI ticks (384 per quarter)
// and resolved through the tempo map at render time, so nothing is quantised.
//
// What is mine:
//   - STACCATO: the score marks nearly everything staccato/marcato; LilyPond's MIDI keeps
//     written durations, so SHORTEN trims them to get the march's bite.
//   - DYNAMICS: LilyPond's dynamic levels mapped by VEL into GM velocity.
//   - THE BAND: the tuba, pizzicato strings and trumpet are not new notes. They take the
//     reduction's own voices — lowest pitch -> tuba (GM tuba sounds an octave down, so it
//     is written an octave up), lower staff's upper voice -> pizzicato strings, top voice
//     -> trumpet. The drum part is Sousa's grid: bass drum on both half-note beats, snare
//     backbeat, crash where the score first reaches ff.
//
//   node audio/render.mjs audio/scores/stars_and_stripes_march.mjs audio/build/stars_and_stripes_march.wav
