function notes(rows_, { shift = 0, velOffset = 0, gain = 1 } = {}) {
  return rows_.map(([t, p, dur, v]) => {
    const st = sec(t);
    return {
      t: st,
      d: Math.max(0.04, sec(t + sounding(dur)) - st),
      p: p + shift,
      v: Math.max(20, Math.min(118, Math.round(VEL(v) * gain + velOffset))),
    };
  });
}

const pianoUpper = notes(UPPER);
const pianoLower = notes(LOWER);
const tuba = notes(BASS_LOW, { shift: 12, velOffset: -6 });
const pizz = notes(BASS_HIGH, { shift: 0, velOffset: -8 });
const trumpet = notes(TOP_VOICE, { velOffset: -10 });
const drumNotes = DRUMS.map(([t, p, v]) => ({ t: sec(t), d: 0.14, p, v: Math.max(20, Math.min(118, v)) }));

const end = Math.max(
  ...pianoUpper.map((n) => n.t + n.d),
  ...pianoLower.map((n) => n.t + n.d),
  ...drumNotes.map((n) => n.t + n.d),
) + 1.6;

