// LilyPond dynamic level -> GM velocity (p ~ mf ~ f ~ ff)
const VEL = (v) => {
  const T = [[69, 46], [90, 72], [101, 86], [114, 100], [123, 110], [127, 112]];
  if (v <= T[0][0]) return T[0][1];
  for (let i = 0; i < T.length - 1; i++) {
    if (v <= T[i + 1][0]) {
      const f = (v - T[i][0]) / (T[i + 1][0] - T[i][0]);
      return Math.round(T[i][1] + f * (T[i + 1][1] - T[i][1]));
    }
  }
  return T[T.length - 1][1];
};

// written duration -> sounding duration (the score's staccato and marcato marks)
const SHORTEN = [
  [240, 0.42],     // eighths
  [480, 0.60],     // sixteenths
  [900, 0.72],     // quarters
  [1400, 0.85],    // dotted quarters
  [99999, 0.90],   // halves and longer
];
function sounding(dur) {
  for (const [lim, f] of SHORTEN) if (dur <= lim) return Math.max(24, Math.round(dur * f));
  return dur;
}

