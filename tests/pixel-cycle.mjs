import assert from 'node:assert/strict';
import { createPixelCycle, paintPixelCharacter, cycleFrame } from '../web/src/characters/wren/pixel-cycle.js';
assert.equal(cycleFrame(0),0); assert.equal(cycleFrame(2),0); assert.equal(cycleFrame(1.99),23);
assert.equal(cycleFrame(-0.01),23);
const cycle=createPixelCycle();
const first=paintPixelCharacter(cycle.sample(0));
const pull=paintPixelCharacter(cycle.sample(10/12));
const end=paintPixelCharacter(cycle.sample(23/12));
assert.equal(first.data.length,first.w*first.h*4);
assert.deepEqual(first.data,end.data,'procedural cycle must close exactly');
assert.deepEqual(first.feet,pull.feet,'foot targets remain planted');
assert.notDeepEqual(first.data,pull.data,'pull must change the painting');
assert.deepEqual(first.data,paintPixelCharacter(cycle.sample(0)).data,'reverse sampling is deterministic');
let visible=0;
for(let i=0;i<first.data.length;i+=4) if(first.data[i+3]>0)visible++;
assert.ok(visible>5000 && visible<first.w*first.h/2,'character silhouette has sensible coverage');
assert.ok(first.grip.every(Number.isFinite) && pull.grip.every(Number.isFinite));
cycle.dispose();
console.log(`Pixel cycle passed: ${visible} painted pixels, fixed feet, exact loop and deterministic repainting.`);
